import streamlit as st
import streamlit.components.v1 as components
from ydata_profiling import ProfileReport
import pandas as pd
from database.db import get_db
from services.data_manager import get_user_datasets, load_dataset_as_df
from visualizations.charts import plot_histogram, plot_scatter, plot_box, plot_correlation_heatmap, plot_bar, plot_pie, plot_line, plot_violin, plot_3d_scatter
from utils.ui_utils import load_css, brand, page_header, require_login

st.set_page_config(page_title="Exploratory Analysis | OmniMetrics", page_icon="📊", layout="wide")
load_css(); brand(); require_login()
page_header("Exploratory data analysis", "Understand distributions, relationships and data quality through interactive exploration.", "ANALYTICS STUDIO")
db = next(get_db()); datasets = get_user_datasets(db, st.session_state["user_id"])
if not datasets: st.info("Upload a dataset to begin exploring."); st.stop()
lookup = {ds.name: ds for ds in datasets}
selected = st.selectbox("Dataset", list(lookup)); ds = lookup[selected]
try: df = load_dataset_as_df(ds)
except Exception as exc: st.error(f"Could not load dataset: {exc}"); st.stop()
num_cols = df.select_dtypes(include=["number"]).columns.tolist()
cat_cols = df.select_dtypes(include=["object","category"]).columns.tolist()
a,b,c,d = st.columns(4)
a.metric("Records", f"{len(df):,}"); b.metric("Features", len(df.columns)); c.metric("Numeric features", len(num_cols)); d.metric("Missing cells", f"{int(df.isna().sum().sum()):,}")
profile_state_key = f"om_profile_html_{selected}"
charts_tab, profile_tab = st.tabs(["Interactive visualizations", "Automated profiling"])
with charts_tab:
    controls, visual = st.columns([1,2.1])
    with controls:
        chart = st.selectbox("Visualization", ["Correlation Heatmap","Histogram","Scatter Plot","Box Plot","Bar Chart","Pie Chart","Line Chart","Violin Plot","3D Scatter"])
        x = y = z = color = None
        all_cols = df.columns.tolist()
        if chart == "Histogram":
            x = st.selectbox("Feature", all_cols); color = st.selectbox("Color by", ["None"]+all_cols)
        elif chart == "Pie Chart":
            x = st.selectbox("Category", cat_cols or all_cols); y = st.selectbox("Values", ["None"]+num_cols)
        elif chart == "3D Scatter":
            if len(num_cols) >= 3:
                x = st.selectbox("X axis", num_cols, index=0); y = st.selectbox("Y axis", num_cols, index=1); z = st.selectbox("Z axis", num_cols, index=2); color = st.selectbox("Color by", ["None"]+all_cols)
            else: st.warning("Three numerical columns are required.")
        elif chart != "Correlation Heatmap":
            x = st.selectbox("X axis", all_cols); y = st.selectbox("Y axis", num_cols or all_cols); color = st.selectbox("Color by", ["None"]+all_cols)
        if color == "None": color = None
        if y == "None": y = None
    with visual:
        st.markdown("### Visualization canvas")
        try:
            if chart == "Correlation Heatmap": fig = plot_correlation_heatmap(df)
            elif chart == "Histogram": fig = plot_histogram(df,x,color)
            elif chart == "Scatter Plot": fig = plot_scatter(df,x,y,color)
            elif chart == "Box Plot": fig = plot_box(df,x,y,color)
            elif chart == "Bar Chart": fig = plot_bar(df,x,y,color)
            elif chart == "Pie Chart": fig = plot_pie(df,x,y)
            elif chart == "Line Chart": fig = plot_line(df,x,y,color)
            elif chart == "Violin Plot": fig = plot_violin(df,x,y,color)
            elif chart == "3D Scatter" and x and y and z: fig = plot_3d_scatter(df,x,y,z,color)
            else: fig = None
            if fig is not None:
                try:
                    fig.update_layout(template="plotly_dark",paper_bgcolor="rgba(0,0,0,0)",plot_bgcolor="rgba(0,0,0,0)",font_color="#dce7fa",margin=dict(l=20,r=20,t=45,b=20))
                except Exception: pass
                st.plotly_chart(fig, use_container_width=True)
        except Exception as exc: st.error(f"Could not render this visualization: {exc}")
with profile_tab:
    st.markdown("### Automated dataset profile")
    st.caption("A detailed HTML report generated by ydata-profiling. Large datasets may take longer to process.")
    if st.button("Generate profiling report", type="primary"):
        with st.spinner("Profiling dataset..."):
            try:
                report = ProfileReport(df, minimal=True, title=f"Profile: {selected}")
                html = report.to_html()
                st.session_state[profile_state_key] = html
            except Exception as exc: st.error(f"Profiling failed: {exc}")
    if st.session_state.get(profile_state_key):
        components.html(st.session_state[profile_state_key], height=1000, scrolling=True)
